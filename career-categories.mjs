export function isCareerJobTitle(title) {
  const cleanTitle = title.trim();
  return cleanTitle.length > 2 && !/^(?:faq|personal information|career site cookie settings|cookie settings)$/i.test(cleanTitle) && jobTitleRole.test(cleanTitle);
}

export function classifyCareerTitle(title) {
  for (const [pattern, category] of careerTitlePatterns) {
    if (pattern.test(title)) return category;
  }
  return 'Other';
}
